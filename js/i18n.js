  const LANGS = { en: "English", ro: "Română" };
  const STORE_KEY = "spikeCoach.v1";

  function detect() {
    try {
      const saved = JSON.parse(localStorage.getItem(STORE_KEY) || "null");
      if (saved && saved.profile && STRINGS[saved.profile.lang]) return saved.profile.lang;
    } catch (e) { /* storage blocked */ }
    const prefs = typeof navigator !== "undefined" ? (navigator.languages || [navigator.language]) : [];
    for (const l of prefs) {
      const code = String(l || "").slice(0, 2).toLowerCase();
      if (STRINGS[code]) return code;
    }
    return "en";
  }

  let lang = detect();

  function t(key, vars = {}) {
    const s = key in STRINGS[lang] ? STRINGS[lang][key] : STRINGS.en[key];
    if (s === undefined) return key;
    return typeof s === "function" ? s(vars) : s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : ""));
  }

  // Fills [data-i18n] text, [data-i18n-label] aria-labels and [data-i18n-title] titles.
  function apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-label]").forEach(el => el.setAttribute("aria-label", t(el.dataset.i18nLabel)));
    root.querySelectorAll("[data-i18n-title]").forEach(el => el.setAttribute("title", t(el.dataset.i18nTitle)));
    if (root.documentElement) root.documentElement.lang = lang;
  }

  return {
    t, apply, detect, LANGS,
    keys: code => Object.keys(STRINGS[code] || {}),
    get lang() { return lang; },
    set(code) { if (STRINGS[code]) lang = code; },
  };
